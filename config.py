"""Configuration settings for Video Summarizer"""

import os
from pathlib import Path

# Directories
BASE_DIR = Path(__file__).parent
UPLOAD_FOLDER = BASE_DIR / "uploads"
OUTPUT_FOLDER = BASE_DIR / "output"
TEMP_FOLDER = BASE_DIR / "temp"

# Create directories if they don't exist
for folder in [UPLOAD_FOLDER, OUTPUT_FOLDER, TEMP_FOLDER]:
    folder.mkdir(exist_ok=True)

# File Settings
ALLOWED_EXTENSIONS = {'mp4', 'avi', 'mov', 'mkv', 'flv', 'wmv'}
MAX_FILE_SIZE = 500 * 1024 * 1024  # 500MB

# Keyframe Extraction Settings
MOTION_THRESHOLD = 30  # Motion detection threshold
HISTOGRAM_THRESHOLD = 0.7  # Scene change detection threshold
MIN_FRAME_INTERVAL = 30  # Minimum frames between keyframes (1 sec at 30fps)
MAX_KEYFRAMES = 20  # Maximum number of keyframes to extract

# Audio Processing Settings
WHISPER_MODEL = "base"  # Options: tiny, base, small, medium, large
WHISPER_LANGUAGE = None  # Auto-detect language

# AI Vision API Settings (for image captions)
GEMINI_API_KEY = os.getenv("GEMINI_API_KEY", "")  # Set via environment variable
USE_GEMINI_VISION = True  # Set to True to use Gemini Flash for captions
GEMINI_MODEL = "gemini-2.5-flash-lite"  # Gemini model for image captioning

# Gemini Video Processing (NEW - processes entire video)
USE_GEMINI_VIDEO = False  # Set to True to use Gemini's native video processing
# When True: Gemini analyzes entire video (visual + audio) in one API call
# When False: Uses traditional pipeline (OpenCV keyframes + Whisper + Gemini summary)

# Summary Settings (for content-focused presentations)
SUMMARY_SLIDES_COUNT = 5  # Number of summary slides to create (excluding title)
SELECT_KEY_VISUALS = True  # Only include most important keyframes

# Summarization Settings
SUMMARY_MAX_LENGTH = 500  # Maximum words in summary
SLIDES_PER_KEYFRAME = True  # Create one slide per keyframe

# PowerPoint Settings
PPT_TITLE = "Video Summary"
